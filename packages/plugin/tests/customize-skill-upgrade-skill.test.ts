/**
 * Pins in /customize's Step 0 for the `upgrade-skill/` directory: the
 * fallback copy of the /upgrade skill that `--upgrade` generates under
 * `.groundwork/`. It must be ignored when classifying `.groundwork/`, sit in
 * the interrupted-run condition's allowed set, and never be edited.
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const step0 = (): string =>
  readFileSync(
    join(here, "..", "skills", "customize", "step-0-reconcile.md"),
    "utf8",
  ).replace(/\s+/g, " ");

describe("step-0-reconcile.md -- upgrade-skill/ is not part of the adopt state", () => {
  it("names upgrade-skill/ as the fallback copy of the /upgrade skill generated by --upgrade", () => {
    const text = step0();
    expect(text).toMatch(/`upgrade-skill\/`/);
    expect(text).toMatch(/fallback copy/i);
    expect(text).toMatch(
      /`upgrade-skill\/`[^.]*generated by `--upgrade`|generated by `--upgrade`[^.]*`upgrade-skill\/`/i,
    );
  });

  it("never counts upgrade-skill/ when classifying .groundwork/, next to the upgrade/ note", () => {
    const text = step0();
    const at = text.indexOf("`upgrade/`");
    expect(at).toBeGreaterThan(-1);
    const note = text.slice(at, at + 400);
    expect(note).toMatch(/upgrade-skill\//);
    expect(note).toMatch(/never count/i);
    expect(note).toMatch(/never edit or delete/i);
  });

  it("allows upgrade-skill/ in the interrupted-run condition's allowed set", () => {
    const text = step0();
    const at = text.indexOf("holds anything other than");
    expect(at).toBeGreaterThan(-1);
    const condition = text.slice(at, at + 260);
    expect(condition).toMatch(/`upgrade\/`/);
    expect(condition).toMatch(/`upgrade-skill\/`/);
  });
});
