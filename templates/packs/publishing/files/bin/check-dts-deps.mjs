/**
 * Checks that every package a published `.d.ts` file imports by bare
 * specifier is declared in `package.json`'s `dependencies` (or
 * `peerDependencies`) -- not only `devDependencies`, and not left
 * undeclared entirely. A type import from a `devDependencies`-only package
 * type-checks fine inside this repo (the dev dependency is installed here)
 * but breaks a consumer's own `tsc`, since npm never installs
 * `devDependencies` for a package's dependents. `publint`/`attw` don't catch
 * this specific case, which is why it's a separate gate.
 *
 * Also honors `/// <reference types="x" />` directives (a common way a
 * `.d.ts` pulls in ambient types), which the plain import/export scan below
 * would miss entirely since triple-slash directives are stripped as
 * comments before that scan runs. `types="node"` is exempt: `@types/node`
 * is a near-universal ambient dev convenience most consumers already carry
 * on their own, not something this package should have to declare as a
 * real dependency just because it uses a Node builtin type.
 *
 * A declared package satisfies either its own name or its `@types/<name>`
 * counterpart (`@types/<scope>__<name>` for a scoped `@scope/<name>`) --
 * many packages only ship (or only need) the `@types/*` package, not the
 * runtime one.
 *
 * A no-op (`checked: 0`, exit 0), not a failure, when:
 * - `package.json` has `private: true` (the baseline's own default) -- a
 *   private package publishes no `.d.ts` files to anyone.
 * - `dist/` does not exist yet (this step runs in the `build` verify group,
 *   after the `build` step itself -- see bin/lib/verify-steps.mjs).
 * - `dist/` exists but contains no `.d.ts`/`.d.mts`/`.d.cts` file -- if this
 *   package is NOT private and really does mean to publish, this is worth a
 *   second look (a build that emits nothing, or a `tsconfig`/`exports`
 *   pointing declarations somewhere other than `dist/`), which the log
 *   message below says explicitly rather than only "skipping".
 */
import process from "node:process";
import { isBuiltin } from "node:module";
import { existsSync, readFileSync, readdirSync, realpathSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(fileURLToPath(import.meta.url), "..", "..");

const DTS_EXTENSIONS = new Set([".d.ts", ".d.mts", ".d.cts"]);

function dtsExtensionOf(fileName) {
  for (const ext of DTS_EXTENSIONS) {
    if (fileName.endsWith(ext)) return ext;
  }
  return undefined;
}

/** Every `.d.ts`/`.d.mts`/`.d.cts` file under `dir`, recursively. */
function listDtsFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...listDtsFiles(full));
    } else if (dtsExtensionOf(entry.name) !== undefined) {
      out.push(full);
    }
  }
  return out;
}

/**
 * Every `/// <reference types="x" />` directive's `x`, extracted BEFORE
 * comment-stripping (a triple-slash directive is syntactically a line
 * comment, so it would otherwise vanish along with ordinary comments).
 */
function referenceTypeNamesIn(content) {
  const names = new Set();
  const pattern = /^\/\/\/\s*<reference\s+types\s*=\s*["']([^"']+)["']\s*\/>/gm;
  for (const match of content.matchAll(pattern)) {
    const name = match[1];
    if (name !== undefined) names.add(name);
  }
  return names;
}

/**
 * A conservative comment strip: block comments unconditionally, and a line
 * comment only when the `//` isn't immediately preceded by `:` (so a
 * `"https://example.com"` string literal survives). Not a full tokenizer --
 * `.d.ts` output is machine-generated by `tsc`, not hand-written prose, so
 * this heuristic is proportionate to what actually shows up there.
 */
function stripComments(content) {
  return content
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|[^:])\/\/.*$/gm, "$1");
}

/**
 * Every bare-specifier import/export/`import()` target in `content` --
 * a deliberately simple regex scan, not a TypeScript AST parse. A relative
 * specifier (starting with `.` or `/`) is never a package dependency, so
 * only a bare specifier is returned. `content` should already have comments
 * stripped (see {@link stripComments}), or a specifier-shaped string inside
 * a doc comment (an `@example` importing from some other package, say)
 * would be flagged as a real dependency.
 */
function bareSpecifiersIn(content) {
  const specifiers = new Set();
  const pattern =
    /(?:from|import)\s*\(?\s*["']([^"']+)["']|require\(\s*["']([^"']+)["']\s*\)/g;
  for (const match of content.matchAll(pattern)) {
    const specifier = match[1] ?? match[2];
    if (
      specifier !== undefined &&
      !specifier.startsWith(".") &&
      !specifier.startsWith("/")
    ) {
      specifiers.add(specifier);
    }
  }
  return specifiers;
}

/** A bare specifier's package name: `@scope/name` keeps its scope, `name/sub/path` is trimmed to `name`. */
export function packageNameOf(specifier) {
  const parts = specifier.split("/");
  if (specifier.startsWith("@")) {
    return parts.slice(0, 2).join("/");
  }
  return parts[0];
}

/** The `@types/*` package name that would satisfy a declared-dependency check for `packageName`. */
function typesPackageNameFor(packageName) {
  if (packageName.startsWith("@")) {
    const scoped = packageName.slice(1).split("/");
    return `@types/${scoped[0]}__${scoped[1] ?? ""}`;
  }
  return `@types/${packageName}`;
}

/**
 * @param {Map<string, string>} dtsFiles path -> content
 * @param {{ dependencies?: Record<string, string>, peerDependencies?: Record<string, string> }} pkg
 * @returns {{ packageName: string, files: string[] }[]} every package name
 * referenced by a `.d.ts` import (or `/// <reference types="..." />`) that
 * isn't declared as a real dependency (by its own name or its `@types/*`
 * counterpart), each with the file(s) that reference it.
 */
export function findUndeclaredTypeDeps(dtsFiles, pkg) {
  const declared = new Set([
    ...Object.keys(pkg.dependencies ?? {}),
    ...Object.keys(pkg.peerDependencies ?? {}),
  ]);
  const byPackage = new Map();

  const record = (path, packageName) => {
    if (packageName === pkg.name) return;
    if (isBuiltin(packageName)) return;
    if (
      declared.has(packageName) ||
      declared.has(typesPackageNameFor(packageName))
    )
      return;
    const files = byPackage.get(packageName) ?? [];
    files.push(path);
    byPackage.set(packageName, files);
  };

  for (const [path, rawContent] of dtsFiles) {
    for (const referenceName of referenceTypeNamesIn(rawContent)) {
      if (referenceName === "node") continue;
      record(path, referenceName);
    }
    for (const specifier of bareSpecifiersIn(stripComments(rawContent))) {
      record(path, packageNameOf(specifier));
    }
  }

  return [...byPackage.entries()].map(([packageName, files]) => ({
    packageName,
    files,
  }));
}

function main() {
  const pkgPath = join(repoRoot, "package.json");
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));

  if (pkg?.private === true) {
    console.log("check-dts-deps: package.json is private -- skipping");
    return;
  }

  const distDir = join(repoRoot, "dist");
  const dtsPaths = listDtsFiles(distDir);
  if (dtsPaths.length === 0) {
    console.log(
      "check-dts-deps: no dist/**/*.d.ts found -- skipping (if this package means to publish " +
        'type declarations, check the build output path and package.json\'s "types"/"exports")',
    );
    return;
  }

  const dtsFiles = new Map(
    dtsPaths.map((path) => [path, readFileSync(path, "utf8")]),
  );
  const undeclared = findUndeclaredTypeDeps(dtsFiles, pkg);

  if (undeclared.length > 0) {
    console.error(
      `check-dts-deps: ${undeclared.length} package(s) are referenced by a published .d.ts file ` +
        "but are not declared in dependencies/peerDependencies (a devDependencies-only or " +
        "undeclared package breaks a consumer's own typecheck):",
    );
    for (const { packageName, files } of undeclared) {
      console.error(`  ${packageName} (from ${files.join(", ")})`);
    }
    process.exitCode = 1;
    return;
  }

  console.log(
    `check-dts-deps: ok -- checked ${dtsPaths.length} declaration file(s)`,
  );
}

if (
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === realpathSync(process.argv[1])
) {
  main();
}
