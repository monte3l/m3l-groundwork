      // regenerated by re-running the CLI, never hand-maintained source.
      ".groundwork/**",
      // A verbatim copy of packages/plugin/src/*.ts, placed here by the
      // CLI's plugin install so /customize is self-contained (its own
      // SKILL.md says so). Not covered by any tsconfig project, and linting
      // a copy would be redundant with -- and could drift from -- linting
      // the original.
