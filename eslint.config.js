      "**/dist/**",
      "**/node_modules/**",
      "**/coverage/**",
      "templates/**",
      "packages/cli/templates/**",
      "packages/cli/plugin/**",
      // A background agent's worktree (see .prettierignore) is a full
      // second checkout under here; never lint it as part of this one.
